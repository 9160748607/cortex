/* ---------------------------------------------------------------------------
   V8.1.1 - Data quality results history table

   First script in the 08_data_quality range. Creates the table that records one
   row per check per run, which is what gives the check set a history and
   therefore the ability to show regression rather than only current state.

   This table is the substitute for SNOWFLAKE.LOCAL.DATA_QUALITY_MONITORING_RESULTS,
   which does not exist on this account - Data Quality Monitoring is an Enterprise
   Edition feature and this account is STANDARD. Reasoning and the measurement in
   08_data_quality/README.md.

   PLACEMENT
   --------------------------------------------------------------------
     Schema      COMMON, not GOVERNANCE.
                 Rule 3 reserves the GOVERNANCE *database* for tag and policy
                 DEFINITIONS. This is a utility that reads environment data and
                 writes environment history, so it belongs to the environment
                 database. COMMON is documented as holding "file formats, stages,
                 sequences, UDFs and procedures".

     Tagging     NOT tagged explicitly. MEDALLION_LAYER = 'COMMON' is applied to
                 the COMMON schema in V2.1.4, and tables inherit their schema's
                 value - the exact mechanism V1.1.4's header describes for
                 satisfying architectural note 6 without per-table tagging.
                 Verified: TAG_REFERENCES on SALES_DEV.COMMON returns
                 MEDALLION_LAYER=COMMON at level SCHEMA.

     object_type TRANSIENT in dev/qa, empty in prod, per architectural note 1.
                 Check history is reproducible by re-running the procedure, so
                 there is no case for fail-safe on it.

   GRAIN
   --------------------------------------------------------------------
     One row per (run_id, check_name). 31 rows per run at present.

     run_id      UUID_STRING() generated by the procedure, so all rows from one
                 invocation share it. Not a sequence - V3.1.3's sequences are
                 unusable here for the same reason they are unusable in dynamic
                 tables, and a UUID needs no coordination.
     passed      Stored, not derived at read time, so history stays truthful if a
                 threshold in V8.1.2 is later tightened. A run records the verdict
                 that was reached ON THE DAY, which is the whole point of history.
     comparator  '=' or '<='. Stored alongside threshold so the recorded verdict
                 is self-describing without consulting the view definition.
     severity    CRITICAL / HIGH / MEDIUM. Drives whether a failure is worth
                 waking someone for; see V8.1.3 for how it is used in the alert.

   Idempotent: IF NOT EXISTS (architectural note 5).
   --------------------------------------------------------------------------- */

CREATE {{ object_type }} TABLE IF NOT EXISTS {{ database }}.COMMON.dq_results (
  run_id        VARCHAR       COMMENT 'UUID shared by every check in one run.',
  measured_at   TIMESTAMP_NTZ COMMENT 'When the run executed.',
  layer         VARCHAR       COMMENT 'Medallion layer under test. SILVER today.',
  table_name    VARCHAR       COMMENT 'Silver table the check ran against.',
  check_name    VARCHAR       COMMENT 'Stable identifier, unique within a run.',
  check_type    VARCHAR       COMMENT 'NULL_COUNT | DUPLICATE_COUNT | REFERENTIAL | ACCEPTED_VALUES | FLAG_COUNT | PARITY | LAG.',
  metric_value  NUMBER        COMMENT 'Measured value.',
  threshold     NUMBER        COMMENT 'Value compared against.',
  comparator    VARCHAR       COMMENT 'Comparison applied: = or <=.',
  passed        BOOLEAN       COMMENT 'Verdict AS AT the run - deliberately stored, not re-derived.',
  severity      VARCHAR       COMMENT 'CRITICAL | HIGH | MEDIUM.'
)
COMMENT = 'Data quality check history, one row per check per run. Written by COMMON.sp_run_silver_dq_checks. Substitute for Enterprise-only DMF result views.';


/* ---------------------------------------------------------------------------
   VALIDATION
   --------------------------------------------------------------------------- */

-- Table exists with the expected 11 columns.
SELECT COUNT(*) AS column_count
FROM   {{ database }}.INFORMATION_SCHEMA.COLUMNS
WHERE  table_schema = 'COMMON' AND table_name = 'DQ_RESULTS';
-- Recorded: 11

-- MEDALLION_LAYER is inherited from the schema, satisfying note 6 without an
-- explicit ALTER ... SET TAG on this table.
SELECT tag_name, tag_value, level
FROM   TABLE({{ database }}.INFORMATION_SCHEMA.TAG_REFERENCES(
         '{{ database }}.COMMON.dq_results', 'TABLE'))
WHERE  tag_name = 'MEDALLION_LAYER';
-- Recorded: MEDALLION_LAYER / COMMON / SCHEMA

-- Empty on creation; V8.1.3's procedure is what populates it.
SELECT COUNT(*) AS row_count FROM {{ database }}.COMMON.dq_results;
-- Recorded: 0
